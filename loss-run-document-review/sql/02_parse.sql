-- 02_parse.sql
-- Parse each PDF with AI_PARSE_DOCUMENT (LAYOUT + page_split), then flatten to one row per page.
-- AI_PARSE_DOCUMENT does not accept .eml; AI_EXTRACT does, so emails skip this step.

USE SCHEMA LOSS_RUN_DEMO.PIPELINE;
USE WAREHOUSE LOSS_RUN_WH;

CREATE OR REPLACE TABLE PARSED_DOCUMENTS (
    FILE_PATH     VARCHAR,
    PARSE_RESULT  VARIANT,
    PAGE_COUNT    INT,
    PARSED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

INSERT INTO PARSED_DOCUMENTS (FILE_PATH, PARSE_RESULT, PAGE_COUNT)
SELECT
    RELATIVE_PATH,
    PARSED,
    PARSED:metadata:pageCount::INT
FROM (
    SELECT
        RELATIVE_PATH,
        AI_PARSE_DOCUMENT(
            TO_FILE('@LOSS_RUN_DEMO.PIPELINE.DOCS', RELATIVE_PATH),
            {'mode': 'LAYOUT', 'page_split': TRUE}
        ) AS PARSED
    FROM DIRECTORY(@LOSS_RUN_DEMO.PIPELINE.DOCS)
    WHERE RELATIVE_PATH ILIKE '%.pdf'
);

CREATE OR REPLACE TABLE DOCUMENT_PAGES AS
SELECT
    d.FILE_PATH,
    p.value:index::INT      AS PAGE_INDEX,
    p.value:content::VARCHAR AS PAGE_CONTENT,
    d.PAGE_COUNT
FROM PARSED_DOCUMENTS d,
     LATERAL FLATTEN(input => d.PARSE_RESULT:pages) p;
